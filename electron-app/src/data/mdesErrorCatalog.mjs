export function searchMdesErrors(query = '', stage = 'All') {
  const needles = query.trim().toLowerCase().split(/\s+/).filter(Boolean)
  return MDES_ERROR_CATALOG.filter((item) => {
    if (stage !== 'All' && item.stage !== stage) return false
    if (!needles.length) return true
    const haystack = [
      item.code, item.title, item.stage, item.meaning, item.retry,
      ...item.causes, ...item.actions,
    ].join(' ').toLowerCase()
    return needles.every(needle => haystack.includes(needle))
  })
}
